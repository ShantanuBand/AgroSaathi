export function translateName(name: string | undefined | null, lang: Language = 'mr'): string {
  if (!name) return lang === 'mr' ? 'शेतकरी' : 'Farmer';
  if (lang !== 'mr') return name.split(' ').map(w => w ? w.charAt(0).toUpperCase() + w.slice(1).toLowerCase() : '').join(' ');

  const trimmed = name.trim();
  if (MARATHI_DICTIONARY[trimmed]) return MARATHI_DICTIONARY[trimmed];
  const lowerFull = trimmed.toLowerCase();
  if (MARATHI_DICTIONARY[lowerFull]) return MARATHI_DICTIONARY[lowerFull];

  const words = trimmed.split(/\s+/);
  const translatedWords = words.map((w) => {
    if (MARATHI_DICTIONARY[w]) return MARATHI_DICTIONARY[w];
    const lower = w.toLowerCase();
    if (MARATHI_DICTIONARY[lower]) return MARATHI_DICTIONARY[lower];
    const capitalized = w.charAt(0).toUpperCase() + w.slice(1).toLowerCase();
    if (MARATHI_DICTIONARY[capitalized]) return MARATHI_DICTIONARY[capitalized];
    return w;
  });

  return translatedWords.join(' ');
}


